export const heroPosOf = (src) => {
  const m = String(src || '').match(/\/images\/(icon|exhibits)\/([^/]+?)(?:-large)?\.webp$/);
  if (!m) return 't';
  const table = m[1] === 'exhibits' ? EXHIBIT_HERO_POS : HERO_POS;
  return table[m[2]] || 't';
};
