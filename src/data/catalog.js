// =====================================================
// Countopia Stats - 指標カタログ定義
// src/data/catalog.js
//
// 「お役立ち統計100」に向けた指標の一覧。汎用ビューア実装前の
// データ定義フェーズの成果物。実際のデータ取得・表示は当面
// 既存の各libファイル（population.js等）が個別に担う。
// このファイルは指標の棚卸し・検索インデックスとして機能する。
//
// スキーマ:
//   key         内部識別子（スラッグ）
//   label       表示名
//　　category    生活場面カテゴリ（population/education/work/housing/money/time/finance/nature/health/culture）
//   ※重要：categoryは指標そのものの性質で決める。使われているページ(usedIn)では決めない。
//     1ページが複数カテゴリの指標を組み合わせて構成されることは多いが(例:暮らしの見積所=work+housing)、
//     各指標のcategoryタグは常に単体で見た時の本来の分類を保つこと。今後カテゴリを追加する際も
//     体系記号(A〜M)から機械的に判断する: A→population, D→finance, E→education, F→work,
//     H→housing, L/G→money, M→time が目安。
//   system      体系コード（内部メタ、e-Stat社会・人口統計体系の分類記号）
//   scope       'pref' | 'muni' | 'both'（都道府県版/市区町村版/両方）
//   statsDataId { pref?, muni? }  粒度ごとの統計表ID
//   fetchMode   'code' | 'keyword' | 'derived'
//     - 'code'    : cat01コードで直接取得（population.js等の標準方式）
//     - 'keyword' : 軸名をキーワード検索して抽出（estat.js方式。生活時間系）
//     - 'derived' : 他の指標から自作計算（rate/割合など）
//   code        cat01コード。文字列 or 複数指標なら配列（fetchMode='code'のとき）
//   needsHash   社会生活統計指標系で#プレフィックスが必要か
//   keyword     軸名検索キーワード（fetchMode='keyword'のとき）
//   deriveFrom  計算元のコード配列（fetchMode='derived'のとき）
//   deriveNote  計算式の説明（人が読むためのメモ、実装は既存lib側）
//   unit        単位
//   direction   'higher' | 'lower' | 'neutral'（高い方が良い/低い方が良い/中立）
//   points      取得済み時点数（時系列化の目安。多くは12、education系は3）
//   status      'published' | 'candidate'
//   usedIn      既存ページのパス（複数可）
// =====================================================

