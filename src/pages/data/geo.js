// 県の配列から、含まれる地方名を重複なく取り出す
export function regionsOf(list) {
  const seen = [];
  for (const r of list) {
    const name = typeof r === 'string' ? r : r.n;
    const region = REGION_OF[name];
    if (region && !seen.includes(region)) seen.push(region);
  }
  return seen;
}